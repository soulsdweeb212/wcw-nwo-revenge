"""Lists the functions that are still assembly in build.json, grouped by what stands in the way of matching them.

    cd source
    python3 tools/list_nonmatching.py [--md]

Groups: "asm in C" (hand-written routines wrapped in a top-level asm() block by tools/asm_to_c.py; they build as C
objects but are not decompiled), split fragment (cut off at a segment end), hand-written (CP0/TLB/cache/FPU access or hand-scheduled, not expected to become C), has a draft in nonmatching/ (its closest C is kept there), kept as assembly (README notes: matched once or blocked on data layout), and C candidates. `--md` prints
a Markdown table (used for nonmatching/STATUS.md). The groups for the first three come from the lists below."""
import json, re, sys
from pathlib import Path

HAND = {  # README "Hand-written assembly" section
    "func_80026AF0", "func_80026B00", "func_80026C20", "func_80028100", "func_80026C10", "nw2DisableInterrupts",
    "nw2RestoreInterrupts", "func_8001C860", "func_80026C30", "func_80026C80", "func_800266B4", "func_800266FC",
}
FRAG = set()  # first words of a function cut off at a segment end (splat.yaml)
LIBGCC = {"func_800284F4", "func_80028860", "func_80028880", "__divdi3", "__moddi3", "__fixsfdi", "signed64ToFloatTrunc",
          "func_80028528", "func_80028624", "bcmp"}
root = Path(__file__).resolve().parent.parent
B = json.loads((root / "build.json").read_text())
readme = (root / "README.md").read_text()
KEPT = set(re.findall(r"^- `(\w+)`: kept as assembly", readme, re.M))
NEAR = {p.stem for p in (root / "nonmatching").glob("*.c")}

rows = []
for f in B["functions"]:
    c = f.get("c") or f"src/{f['seg']}/{f['name']}.c"
    asm_in_c = (root / c).exists() and "\nasm(" in "\n" + (root / c).read_text()
    if (root / c).exists() and not asm_in_c:
        continue
    t = (root / f["asm"]).read_text(errors="replace")
    size = int(re.search(r"nonmatching \S+, (0x[0-9A-Fa-f]+)", t).group(1), 16)
    n = f["name"]
    low = bool(re.search(r"\b(mfc0|mtc0|tlbwi|cache|eret|tlbr|tlbp)\b|\$k[01]", t)) or "Handwritten" in t
    if asm_in_c:
        grp = "asm in C"
    elif n in HAND or low:
        grp = "hand-written"
    elif n in FRAG:
        grp = "split fragment (segment end)"
    elif n in NEAR:
        grp = "has a draft in nonmatching/"
    elif n in KEPT:
        grp = "kept as assembly"
    elif n in LIBGCC:
        grp = "probably library/libgcc"
    else:
        grp = "C candidate"
    calls = len(re.findall(r"\bjal\b", t))
    rows.append((grp, size, n, f["seg"], "jump table" if "jtbl" in t else "", calls))

order = ["has a draft in nonmatching/", "C candidate", "kept as assembly", "split fragment (segment end)", "probably library/libgcc", "hand-written", "asm in C"]
rows.sort(key=lambda r: (order.index(r[0]), r[1]))
md = "--md" in sys.argv
if md:
    print("# Functions still in assembly\n\nGenerated by `tools/list_nonmatching.py`. Every function listed under 'has a draft' has its closest C in this folder; nonmatching/README.md says what blocks each one.\n")
for g in order:
    sel = [r for r in rows if r[0] == g]
    if not sel:
        continue
    if md:
        print(f"## {g} ({len(sel)})\n\n| function | size | segment | calls | notes |\n|---|---|---|---|---|")
        for _, s, n, seg, jt, c in sel:
            print(f"| `{n}` | 0x{s:X} | {seg} | {c} | {jt} |")
        print()
    else:
        print(f"\n== {g} ({len(sel)})")
        for _, s, n, seg, jt, c in sel:
            print(f"  {n:32s} 0x{s:<5X} {seg:14s} calls={c:<3d} {jt}")
print(f"\n{len(rows)} functions in assembly", file=sys.stderr if md else sys.stdout)
